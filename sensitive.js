function hit(text, list){
  const t = String(text || '');
  return list.filter(w => t.indexOf(w) >= 0);
}
/** 绝对红线：命中即剔除 */
function isHardBlocked(text){
  return hit(text, HARD).length > 0;
}
/** 敏感边缘：保留，降权 + 标黄待复核 */
function softHits(text){ return hit(text, SOFT); }
function isSoftSensitive(text){ return softHits(text).length > 0; }
/** 敏感度分：用于降权 */
function sensitiveScore(text){
  return softHits(text).length * 3 + hit(text, HARD).length * 10;
}
/** 成稿兜底：成稿里出现红线词直接判不合格 */
function containsHardBlock(text){
  return hit(text, HARD).length > 0;
}

